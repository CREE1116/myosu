// Generates src/engine/puzzleSet.ts: four-sequence puzzles from rule-based self-play, sorted into themes.
// Run: npx vite-node scripts/gen-puzzles.ts
import { writeFileSync } from 'node:fs';
import { chooseAIMove } from '../src/engine/ai';
import { analyzeMove, cloneBoard, createEmptyBoard, opponentOf } from '../src/engine/renju';
import { forcedMove } from '../src/engine/strength';
import { findVcfSequence } from '../src/engine/vcf';
import { BLACK, Board, Coord, Player } from '../src/engine/types';
import type { Puzzle, PuzzleTheme } from '../src/engine/puzzle';

const RULES = 'renju' as const;
let seed = 11;
const rand = () => ((seed = (seed * 1103515245 + 12345) & 0x7fffffff) / 0x7fffffff);

function shortestVcf(board: Board, p: Player) {
  let best = findVcfSequence(board, p, RULES, 15, 400);
  while (best && best.length > 1) {
    const shorter = findVcfSequence(board, p, RULES, best.length - 2, 400);
    if (!shorter) break;
    best = shorter;
  }
  return best;
}

function classify(board: Board, attacker: Player, line: Coord[]): { theme: PuzzleTheme; moves: number } {
  const b = cloneBoard(board);
  const def = opponentOf(attacker);
  line.forEach((c, i) => (b[c.row][c.col] = i % 2 === 0 ? attacker : def));
  const last = line[line.length - 1];
  b[last.row][last.col] = 0;
  const finish = analyzeMove(b, last.row, last.col, attacker, RULES);
  // The sequence ends on a four the defender may not block: the block is forbidden.
  if (!finish.isWin) return { theme: 'trap', moves: (line.length + 1) / 2 + 1 };
  const moves = (line.length + 1) / 2;
  return { theme: moves >= 4 ? 'long' : 'chain', moves };
}

function randomNear(board: Board, p: Player) {
  for (let t = 0; t < 200; t++) {
    const r = 3 + Math.floor(rand() * 9), c = 3 + Math.floor(rand() * 9);
    if (analyzeMove(board, r, c, p, RULES).legal) return { row: r, col: c };
  }
  return null;
}

const want: Record<PuzzleTheme, number> = { chain: 12, trap: 8, long: 12, mine: 0 };
const got: Record<PuzzleTheme, Puzzle[]> = { chain: [], trap: [], long: [], mine: [] };
const seenPos = new Set<string>(); // identical self-play games give identical puzzles
const done = () => (Object.keys(want) as PuzzleTheme[]).every((k) => got[k].length >= want[k]);
const started = Date.now();
for (let game = 0; game < 20000 && !done() && Date.now() - started < 1_500_000; game++) {
  const board = createEmptyBoard();
  let p: Player = BLACK;
  for (let ply = 0; ply < 70; ply++) {
    if (ply >= 8 && !forcedMove(board, p, RULES)) {
      const vcf = shortestVcf(board, p);
      if (vcf && vcf.length >= 3) {
        const { theme, moves } = classify(board, p, vcf);
        // A single open four (or a lone forbidden block) is not a 묘수: need two forcing fours first.
        const minLen = theme === 'trap' ? 3 : 5;
        const key = board.flat().join('');
        if (vcf.length >= minLen && got[theme].length < want[theme] && !seenPos.has(key)) {
          seenPos.add(key);
          const black: number[] = [], white: number[] = [];
          board.forEach((row, r) => row.forEach((s, c) => { if (s) (s === BLACK ? black : white).push(r * 15 + c); }));
          got[theme].push({ id: '', theme, black, white, attacker: p, moves, line: vcf.map((c) => c.row * 15 + c.col) });
          console.log(`game ${game}: ${theme} ${moves} moves, ${black.length + white.length} stones`);
        }
        break;
      }
    }
    const mv = ply < 4 || rand() < 0.25 ? randomNear(board, p) : chooseAIMove(board, p, RULES, rand() < 0.5 ? 'lv2' : 'lv3');
    if (!mv) break;
    if (analyzeMove(board, mv.row, mv.col, p, RULES).isWin) break;
    board[mv.row][mv.col] = p;
    p = opponentOf(p);
  }
}
// Within a theme: shorter solutions and fewer stones first.
const all = (['chain', 'trap', 'long'] as PuzzleTheme[]).flatMap((t) =>
  got[t]
    .sort((a, b) => a.moves - b.moves || a.black.length + a.white.length - b.black.length - b.white.length)
    .map((p, i) => ({ ...p, id: `${t}-${i + 1}` })),
);
writeFileSync(
  new URL('../src/engine/puzzleSet.ts', import.meta.url),
  `// Generated by scripts/gen-puzzles.ts — grouped by theme, easy to hard.\nimport type { Puzzle } from './puzzle';\n\nexport const PUZZLES: Puzzle[] = ${JSON.stringify(all)};\n`,
);
console.log(`wrote ${all.length} puzzles`, Object.fromEntries(Object.entries(got).map(([k, v]) => [k, v.length])));
